/// The character the digraph of `first` and `second` stands for; as in
/// Vim, also where it is written the other way round.
pub(super) fn digraph(first: char, second: char) -> Option<char> {
    let find = |a: char, b: char| {
        DIGRAPHS.iter().find_map(|(pair, c)| {
            let mut chars = pair.chars();
            (chars.next() == Some(a) && chars.next() == Some(b)).then_some(*c)
        })
    };
    find(first, second).or_else(|| find(second, first))
}

/// The digraph that types `c`, if there is one.
pub(super) fn digraph_of(c: char) -> Option<&'static str> {
    DIGRAPHS
        .iter()
        .find_map(|(pair, of)| (*of == c).then_some(*pair))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn digraphs_of_vims_table() {
        assert_eq!(digraph('e', ':'), Some('\u{eb}'));
        assert_eq!(digraph(':', 'e'), Some('\u{eb}'), "the other way round");
        assert_eq!(digraph('a', '*'), Some('\u{3b1}'));
        assert_eq!(digraph('s', 's'), Some('\u{df}'));
        assert_eq!(digraph('-', '>'), Some('\u{2192}'));
        assert_eq!(digraph('E', 'u'), Some('\u{20ac}'));
        assert_eq!(digraph('i', 'j'), Some('\u{133}'));
        assert_eq!(digraph('z', '<'), Some('\u{17e}'));
        assert_eq!(digraph('*', 's'), Some('\u{3c2}'));
        assert_eq!(digraph('j', 'a'), Some('\u{44f}'));
        assert_eq!(digraph('q', 'q'), None);
        assert_eq!(digraph_of('\u{eb}'), Some("e:"));
        // Every pair is two characters, and none is there twice.
        let mut pairs: Vec<&str> = DIGRAPHS.iter().map(|(pair, _)| *pair).collect();
        assert!(pairs.iter().all(|pair| pair.chars().count() == 2));
        pairs.sort_unstable();
        pairs.dedup();
        assert_eq!(pairs.len(), DIGRAPHS.len());
    }
}
